package api

import (
	"embed"
	"io/fs"
	"net/http"
	"strings"
)

// dist is the SPA build (web/, Svelte + Vite), embedded in the binary.
//
// Embedding keeps the promise of a single binary: no copying an assets folder
// at install, no path to configure. Since embed requires the files to exist at
// compile time, the interface build is versioned - see web/README.md.
//
//go:embed all:dist
var dist embed.FS

func (s *Server) webHandler() http.Handler {
	sub, err := fs.Sub(dist, "dist")
	if err != nil {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			writeError(w, http.StatusInternalServerError, "interface indisponível")
		})
	}

	files := http.FileServerFS(sub)
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		path := strings.TrimPrefix(r.URL.Path, "/")

		// Files generated by Vite have a hash in the name, so their content
		// never changes and they can be cached forever. index.html is the
		// opposite: it is what points to the new hashes after an update.
		if strings.HasPrefix(path, "assets/") {
			w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
		} else {
			w.Header().Set("Cache-Control", "no-cache")
		}

		files.ServeHTTP(w, r)
	})
}
